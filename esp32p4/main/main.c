//
// main.c - pico-fsynth on the ESP32-P4: start up, the render tasks and
// the status reports. The ESP-IDF counterpart of firmware/main.c.
//
// Tasks:
//   render (core 1, high priority): owns the synth. For each audio buffer,
//     per block: applies queued MIDI (within a time budget), advances the
//     demo song and renders; then hands the buffer to audio_write(), which
//     blocks while the I2S DMA ring is full. That blocking paces it.
//   helper (core 0, high priority, FSYNTH_DUAL_CORE only): renders voice
//     parts 1..FS_RENDER_PARTS-1 of each block. The render task wakes it
//     with a task notification, renders part 0 itself, and waits for the
//     helper's notification before mixing (fs_synth_render_end).
//   main (app_main, core 0, low priority): MIDI input polling and a status
//     line once a second. The helper preempts it whenever it has work.
//
// Start up: the font is found in the "font" partition (partitions.csv) and
// either memory mapped (read through the flash cache, like XIP on the Pico)
// or copied into PSRAM (FSYNTH_FONT_IN_PSRAM, or automatically when it
// reaches past the first 16 MB of flash). Without a usable font the
// firmware only prints the reason every 2 s. A demo song (FS_DEMO_MIDI)
// plays until live MIDI arrives; without one a short arpeggio confirms
// audio.
//
// A small serial command line (console.c) can hold test notes: type help.
// The same serial port also takes raw MIDI (see console.c and
// host/serial_midi.c).
//
// Master volume and EQ are saved in NVS on request (settings.c, SysEx
// F0 7D 46 53 01/02 F7, host/settings.sh) and loaded at start up.
//
// USB MIDI (FSYNTH_USB_MIDI) is on the high-speed USB port; see usb_midi.c.
//
// Not yet ported: the micro benchmarks.
//
